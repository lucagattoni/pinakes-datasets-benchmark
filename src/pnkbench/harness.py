"""Pinakes' own evaluation harness, fed this dataset.

`python -m pinakes.eval` reads `questions.yaml`: a `kind`, the question, the documents that
`expect`ed, optional `filters`. Exporting MultiHop-RAG into that shape lets the numbers sit beside
the ones Pinakes publishes for its own corpora (`tests/demo-kb`, the RFC corpus). The price is the
harness's definition of success, stated here so nobody reads its recall as ours:

* **A hit is any one expected document** in the first k passages. For a question that needs two to
  four articles, that is the lenient reading; the all-evidence numbers in the report are the
  strict one.
* **`multi-hop` carries no `hops`.** Pinakes scores scripted hops query by query; this dataset
  ships one query and its evidence, not a sequence. Writing hops would mean inventing sub-queries,
  so the harness scores these as a single search (its `hops` are optional).
* **Only the filters the harness can express** are exported: `tags` (the category and source
  variants). Its loader reads no `modified_*`, so date windows live in our own run only.

The harness runs on the eval half only, after calibration, so its false-confidence and
false-abstain rates are measured on queries the thresholds were not fitted on.
"""

from __future__ import annotations

import io
import json
import subprocess
import sys
import time
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from ruamel.yaml import YAML

from pnkbench import items as items_module
from pnkbench import layout
from pnkbench.items import RunItem
from pnkbench.multihop_rag import Dataset

EXPORTED_VARIANTS = (items_module.BASE, items_module.F_CAT_TAG, items_module.F_SRC_TAG)
HARNESS_K = 5


def questions_yaml(dataset: Dataset, items: Sequence[RunItem]) -> str:
    """The items as a Pinakes `questions.yaml`. Variants outside `EXPORTED_VARIANTS` are skipped."""
    queries = {q.id: q for q in dataset.queries}
    entries: list[dict[str, Any]] = []
    for item in items:
        if item.variant not in EXPORTED_VARIANTS:
            continue
        query = queries[item.base_id]
        entry: dict[str, Any] = {"id": item.id, "question": item.query}
        if not query.answerable:
            entry["kind"] = "no-answer"
        else:
            entry["kind"] = "filter" if item.variant != items_module.BASE else "multi-hop"
            entry["expect"] = [layout.doc_relpath(a) for a in dataset.gold(query)]
            if item.variant != items_module.BASE:
                entry["filters"] = {"tags": list(item.filters.tags)}
        entries.append(entry)
    yaml = YAML(typ="safe")
    yaml.default_flow_style = False
    yaml.width = 120
    sink = io.StringIO()
    sink.write(
        "# Generated by pnkbench: MultiHop-RAG as a Pinakes golden set. See src/pnkbench/harness.py.\n"
    )
    yaml.dump({"questions": entries}, sink)
    return sink.getvalue()


def run_harness(
    kb_root: Path, run_dir: Path, dataset: Dataset, items: Sequence[RunItem]
) -> dict[str, Any]:
    """Run `python -m pinakes.eval` over the eval half; keep its aggregates and per-question rows."""
    eval_items = [i for i in items if items_module.split_of(i.base_id) == items_module.EVAL]
    out = run_dir / "harness"
    out.mkdir(exist_ok=True)
    questions = out / "questions.yaml"
    questions.write_text(questions_yaml(dataset, eval_items), encoding="utf-8")
    exported = [i for i in eval_items if i.variant in EXPORTED_VARIANTS]

    started = time.monotonic()
    completed = subprocess.run(
        [
            sys.executable,
            "-m",
            "pinakes.eval",
            str(kb_root),
            "--questions",
            str(questions),
            "-k",
            str(HARNESS_K),
            "--write-baseline",
            "--baseline",
            str(out / "baseline.json"),
            "--outcomes",
            str(out / "outcomes.json"),
        ],
        capture_output=True,
        text=True,
        check=False,
    )
    if completed.returncode != 0:
        raise RuntimeError(
            f"pinakes.eval exited {completed.returncode}:\n{completed.stderr[-1000:]}"
        )
    metrics = json.loads(completed.stdout[: completed.stdout.index("\n\nwrote")])
    return {
        "k": HARNESS_K,
        "questions": len(exported),
        "by_variant": {v: sum(1 for i in exported if i.variant == v) for v in EXPORTED_VARIANTS},
        "wall_seconds": round(time.monotonic() - started, 1),
        "metrics": metrics,
        "note": (
            "any-of scoring: a hit is any one expected article among the first k passages; "
            "multi-hop questions carry no scripted hops; eval half only"
        ),
    }
